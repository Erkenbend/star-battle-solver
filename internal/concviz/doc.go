package concviz

import (
	"fmt"
	"strings"
)

// The block of concurrency.md that shows a story lies between these lines;
// UpdateDoc rewrites it.
const (
	docBegin = "<!-- concviz %s: generated by go test ./internal/concviz -update -->"
	docEnd   = "<!-- /concviz -->"
)

// PlayerURL is where .github/workflows/pages.yml publishes the player.
const PlayerURL = "https://erkenbend.github.io/star-battle-solver/"


// DocBlock is the Markdown that shows s in concurrency.md: the sequence
// diagram, a pointer to the player, and the steps.
func (s *Story) DocBlock() string {
	var b strings.Builder
	fmt.Fprintf(&b, docBegin+"\n\n", s.ID())
	fmt.Fprintf(&b, "![Sequence diagram: %s](concurrency/%s)\n\n", s.Title, s.File)
	fmt.Fprintf(&b, "Step through the scene in the [player](%s#%s) (or open [`concurrency/player.html`](concurrency/player.html#%s) from a clone).\n\n", PlayerURL, s.ID(), s.ID())
	for i := 1; i < len(s.frames); i++ {
		fmt.Fprintf(&b, "%d. %s\n", i, s.frames[i].caption)
	}
	b.WriteString("\n" + docEnd)
	return b.String()
}

// UpdateDoc replaces the block of each story in md. Every story must have
// its begin and end lines in md already.
func UpdateDoc(md string, stories []*Story) (string, error) {
	for _, s := range stories {
		begin := fmt.Sprintf(docBegin, s.ID())
		i := strings.Index(md, begin)
		if i < 0 {
			return "", fmt.Errorf("concurrency.md has no line %s", begin)
		}
		j := strings.Index(md[i:], docEnd)
		if j < 0 {
			return "", fmt.Errorf("concurrency.md: no %s after %s", docEnd, begin)
		}
		md = md[:i] + s.DocBlock() + md[i+j+len(docEnd):]
	}
	return md, nil
}
