package observers

import "testing"

// p5 layout (see unitfinish_test.go):
//
//	  01234
//	0 DBBBB
//	1 DDBCC
//	2 DDBAA
//	3 EDDAA
//	4 EAAAA
func TestElimination(t *testing.T) {
	units := p5.Units() // rows 0-4, cols 5-9, regions 10-14
	tests := []struct {
		name          string
		unitIdx       int
		before, after string
	}{
		{"vertical 2x1 region E", 10 + p5.Region(4, 0), `
			.....
			.....
			.....
			.....
			.....`, `
			X....
			X....
			X....
			.X...
			.X...`},
		{"row 2 down to two cells (2,3),(2,4)", 2, `
			.....
			.....
			XXX..
			.....
			.....`, `
			.....
			...XX
			XXX..
			...XX
			.XXXX`},
		{"nothing when unit is spread out", 0, `
			.....
			.....
			.....
			.....
			.....`, `
			.....
			.....
			.....
			.....
			.....`},
	}
	implied := newImpliedTable(p5)
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			expectDeduce(t, p5, Elimination{Unit: units[tt.unitIdx], implied: implied}, tt.before, tt.after)
		})
	}
}
