package observers

import (
	"testing"

	"starbattle/internal/puzzle"
)

// p5 layout (see unitfinish_test.go):
//
//	  01234
//	0 DBBBB
//	1 DDBCC
//	2 DDBAA
//	3 EDDAA
//	4 EAAAA
func TestConfinement(t *testing.T) {
	R, C, G := puzzle.Row, puzzle.Col, puzzle.Region
	tests := []struct {
		name          string
		from, to      puzzle.UnitKind
		k             int
		before, after string
		contiguous    bool
	}{
		{"k=1 region E lies in column 0", G, C, 1, `
			.....
			.....
			.....
			.....
			.....`, `
			X....
			X....
			X....
			.....
			.....`, false},
		{"k=1 row 0 only contains B", R, G, 1, `
			X....
			.....
			.....
			.....
			.....`, `
			X....
			..X..
			..X..
			.....
			.....`, false},
		{"k=1 nothing when row has two colors", R, G, 1, `
			.....
			.....
			.....
			.....
			.....`, `
			.....
			.....
			.....
			.....
			.....`, false},
		{"k=2 rows 3,4 only use columns 0,1", R, C, 2, `
			.....
			.....
			.....
			..XXX
			..XXX`, `
			XX...
			XX...
			XX...
			..XXX
			..XXX`, false},
		{"k=2 nothing when two rows use three columns", R, C, 2, `
			.....
			.....
			.....
			...XX
			..XXX`, `
			.....
			.....
			.....
			...XX
			..XXX`, false},
		{"k=2 regions B,C only in rows 0,1", G, R, 2, `
			.....
			.....
			..X..
			.....
			.....`, `
			X....
			XX...
			..X..
			.....
			.....`, false},
		{"k=2 rows 0,2 only use columns 3,4", R, C, 2, `
			XXX..
			.....
			XXX..
			.....
			.....`, `
			XXX..
			...XX
			XXX..
			...XX
			...XX`, false},
		{"contiguous: k=2 rows 0,2 are not a block", R, C, 2, `
			XXX..
			.....
			XXX..
			.....
			.....`, `
			XXX..
			.....
			XXX..
			.....
			.....`, true},
		{"contiguous: k=2 rows 3,4 only use columns 0,1", R, C, 2, `
			.....
			.....
			.....
			..XXX
			..XXX`, `
			XX...
			XX...
			XX...
			..XXX
			..XXX`, true},
		{"contiguous: k=3 > N/2 rows 2 to 4 only use columns 0 to 2", R, C, 3, `
			.....
			.....
			...XX
			...XX
			...XX`, `
			XXX..
			XXX..
			...XX
			...XX
			...XX`, true},
		{"contiguous: regions still use any subset", G, R, 2, `
			.....
			.....
			..X..
			.....
			.....`, `
			X....
			XX...
			..X..
			.....
			.....`, true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			o := NewConfinement(p5, tt.from, tt.to, tt.k)
			o.Contiguous = tt.contiguous
			expectDeduce(t, p5, o, tt.before, tt.after)
		})
	}
}
